public class Kalkulator {
 public float tambah(int b, int par1, int par2, int a) {
        return a + b;
    }

    public int kurang(int a, int b) {
        return a - b;
    }

    public int kali(int a, int b) {
        return a * b;
    }

    public double bagi(int a, int b) {
        return (double) a / b;
    }
}
